package com.example.stashed.ui

import android.content.Intent
import android.content.SharedPreferences
import android.os.Bundle
import android.util.Log
import android.view.View
import android.widget.Button
import android.widget.EditText
import android.widget.TextView
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import androidx.lifecycle.lifecycleScope
import com.example.stashed.MainActivity
import com.example.stashed.R
import com.example.stashed.data.AppDatabase
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInClient
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.common.SignInButton
import com.google.android.gms.common.api.ApiException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.launch

class LoginActivity : AppCompatActivity() {

    private lateinit var etUsername: EditText
    private lateinit var etPassword: EditText
    private lateinit var btnLogin: Button
    private lateinit var tvError: TextView
    private lateinit var tvGoToRegister: TextView
    private lateinit var sharedPrefs: SharedPreferences

    // Firebase & Google Auth Variables
    private lateinit var auth: FirebaseAuth
    private lateinit var googleSignInClient: GoogleSignInClient

    // Launcher for the Google Account Pop-up
    private val googleSignInLauncher = registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
        if (result.resultCode == RESULT_OK) {
            val task = GoogleSignIn.getSignedInAccountFromIntent(result.data)
            try {
                val account = task.getResult(ApiException::class.java)
                // If successful, pass the token to Firebase
                firebaseAuthWithGoogle(account.idToken!!, account.email, account.displayName)
            } catch (e: ApiException) {
                Log.e("SSO", "Google Sign-In failed", e)
                showError("Google Sign-In Failed: ${e.message}")
            }
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_login)

        sharedPrefs = getSharedPreferences("StashedSession", MODE_PRIVATE)

        // Check if user is already logged in — skip to main if so
        if (sharedPrefs.getInt("userId", -1) != -1) {
            goToMain()
            return
        }

        etUsername     = findViewById(R.id.etUsername)
        etPassword     = findViewById(R.id.etPassword)
        btnLogin       = findViewById(R.id.btnLogin)
        tvError        = findViewById(R.id.tvError)
        tvGoToRegister = findViewById(R.id.tvGoToRegister)

        // Initialize Firebase Auth
        auth = FirebaseAuth.getInstance()

        // Configure Google Sign-In options
        val gso = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestIdToken(getString(R.string.default_web_client_id)) // Auto-generated by google-services.json
            .requestEmail()
            .build()

        googleSignInClient = GoogleSignIn.getClient(this, gso)

        // Link the Google Sign-In Button from the XML
        val btnGoogleSignIn = findViewById<SignInButton>(R.id.btnGoogleSignIn)
        btnGoogleSignIn.setOnClickListener {
            val signInIntent = googleSignInClient.signInIntent
            googleSignInLauncher.launch(signInIntent)
        }

        // Standard Room Database Login
        btnLogin.setOnClickListener {
            val username = etUsername.text.toString().trim()
            val password = etPassword.text.toString().trim()

            if (username.isEmpty() || password.isEmpty()) {
                showError("Please fill in all fields")
                return@setOnClickListener
            }

            lifecycleScope.launch {
                val db   = AppDatabase.getDatabase(applicationContext)
                val user = db.userDao().loginUser(username, password)

                runOnUiThread {
                    if (user != null) {
                        sharedPrefs.edit()
                            .putInt("userId", user.id)
                            .putString("username", user.username)
                            .putString("fullName", user.fullName)
                            .apply()
                        goToMain()
                    } else {
                        showError("Incorrect username or password")
                    }
                }
            }
        }

        tvGoToRegister.setOnClickListener {
            startActivity(Intent(this, RegisterActivity::class.java)) // Keep this if you have a RegisterActivity
        }
    }

    // Authenticate the Google credentials with Firebase
    private fun firebaseAuthWithGoogle(idToken: String, email: String?, displayName: String?) {
        val credential = GoogleAuthProvider.getCredential(idToken, null)
        auth.signInWithCredential(credential)
            .addOnCompleteListener(this) { task ->
                if (task.isSuccessful) {
                    Log.d("SSO", "Firebase Authentication successful!")

                    // Save to SharedPreferences using a special ID (9999) so MainActivity knows it's an SSO user
                    sharedPrefs.edit()
                        .putInt("userId", 9999)
                        .putString("username", email ?: "Google User")
                        .putString("fullName", displayName ?: "User")
                        .apply()

                    goToMain()
                } else {
                    Log.e("SSO", "Firebase Authentication failed", task.exception)
                    showError("Firebase Authentication Failed.")
                }
            }
    }

    private fun showError(message: String) {
        tvError.text = message
        tvError.visibility = View.VISIBLE
    }

    private fun goToMain() {
        startActivity(Intent(this, MainActivity::class.java).apply {
            flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TASK
        })
        finish()
    }
}